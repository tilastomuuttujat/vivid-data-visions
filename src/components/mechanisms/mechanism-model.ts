export function eraOf(year: number) {
  return ERAS.findIndex(
    (e, i) => year >= e.from && (year < e.to || (i === ERAS.length - 1 && year <= e.to)),
  );
}
export function eventDecisions(event: MechanismEvent) {
  return event.decisions.map((id) => DECISIONS.find((d) => d.id === id)!).filter(Boolean);
}
export const timelineX = (year: number) => 230 + ((year - 1850) / 175) * 1190;
export function eventMarkers(mechanism: MechanismId) {
  const last = [-Infinity, -Infinity, -Infinity];
  return EVENTS.filter((e) => e.mechanisms.includes(mechanism)).map((event) => {
    const x = timelineX(event.year);
    let lane = last.findIndex((previous) => x - previous >= 16);
    if (lane < 0) lane = last.indexOf(Math.min(...last));
    last[lane] = x;
    return { event, x, lane };
  });
}
